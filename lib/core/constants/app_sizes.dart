class AppSizes {
  AppSizes._();

  // Spacing
  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;
  static const double xxxl = 48;

  // Radius
  static const double radiusSm = 8;
  static const double radiusMd = 12;
  static const double radiusLg = 16;
  static const double radiusPill = 100;

  // Component heights
  static const double inputHeight = 52;
  static const double buttonHeight = 52;
  static const double logoSize = 56;

  // Splash — logo mark + "zoclips" wordmark reveal
  static const double splashLogoSize = 100;
  static const double splashWordmarkSize = 56;

  // Font sizes
  static const double fontXs = 12;
  static const double fontSm = 14;
  static const double fontMd = 16;
  static const double fontLg = 20;
  static const double fontXl = 24;
  static const double fontXxl = 28;

  // Icon sizes
  static const double iconSm = 16;
  static const double iconMd = 20;
  static const double iconLg = 24;

  // Max width for form card on large/tablet screens
  static const double maxFormWidth = 420;

  // Max width for regular page content on large/tablet screens, so text and
  // lists don't stretch edge-to-edge on wide tablets/iPad/desktop.
  static const double maxPageWidth = 720;

  // Material 3 window size class breakpoints (logical pixels).
  // <breakpointMedium: phones and folded/cover-screen foldables.
  // breakpointMedium..breakpointExpanded: portrait tablets, unfolded foldables.
  // >=breakpointExpanded: landscape tablets, iPad, desktop-class widths.
  static const double breakpointMedium = 600;
  static const double breakpointExpanded = 840;

  // Nav rail width
  static const double navRailWidth = 88;
  static const double navRailExtendedWidth = 220;
